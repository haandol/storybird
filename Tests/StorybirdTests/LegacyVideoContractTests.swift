            defaults.removePersistentDomain(forName: domain)
        }
        return (root, repository, StorybirdStoragePreferences(defaults: defaults))
    }

    private func install(
        _ library: Data,
        in repository: ProjectRepository,
        filenames: [String] = ["recording.mp4", "narration.wav", "unreferenced-original.bin"]
    ) throws {
        try repository.prepare()
        let assets = repository.assetsDirectory(projectID: projectID)
        try FileManager.default.createDirectory(at: assets, withIntermediateDirectories: true)
        // These are preservation sentinels, not playable media. These tests stop
        // before rendering and do not claim native media/codec verification.
        for filename in filenames {
            try Data("Synthetic original bytes: \(filename)".utf8)
                .write(to: assets.appendingPathComponent(filename))
        }
        try library.write(to: repository.rootURL.appendingPathComponent("library.json"))
    }

    private func files(in root: URL) throws -> [String: Data] {
        let enumerator = try XCTUnwrap(FileManager.default.enumerator(
            at: root, includingPropertiesForKeys: [.isRegularFileKey]
        ))
        var result: [String: Data] = [:]
        for case let url as URL in enumerator {
            if try url.resourceValues(forKeys: [.isRegularFileKey]).isRegularFile == true {
                result[String(url.path.dropFirst(root.path.count + 1))] = try Data(contentsOf: url)
            }
        }
        return result
    }

