        let expected = store.projects
        XCTAssertEqual(expected.count, 1)
        let host = StorybirdExternalControlHost(store: store)
        let arguments = try JSONSerialization.data(withJSONObject: [
            "project_id": projectID.uuidString, "expected_revision": 0,
            "time": 0.5, "x": 0.25, "y": 0.75, "text": "Must not be saved",
            "start_time": 0, "end_time": 1, "parent_directory": root.path,
        ])
        // render_preview is the image-producing preview API; preview_project
        // only navigates to the workspace, which displays its unsupported state.
        for name in [
            "storybird_create_click", "storybird_upsert_subtitle",
            "storybird_render_preview", "storybird_export_project",
        ] {
            let response = await host.handle(StorybirdControlRequest(
                name: name, argumentsJSON: arguments
            ))
            XCTAssertTrue(response.isError, "\(name): \(response.text)")
            let expectedError = name == "storybird_create_click"
                ? VideoTimelineEditError.invalidClickPlacement.localizedDescription
                : VideoProjectValidationError.missingRecording.localizedDescription
            XCTAssertTrue(
                response.text.contains(expectedError),
                "\(name) must reject the historical model before media work: \(response.text)"
            )
            XCTAssertEqual(store.projects, expected)
            XCTAssertNil(store.requestedPreviewProjectID)
            XCTAssertFalse(store.isExportActive)
            XCTAssertEqual(try files(in: root), original, name)
        }
        XCTAssertThrowsError(try store.undo(projectID: projectID)) { error in
            XCTAssertEqual(error as? RecordingStoreError, .noUndo)
        }
        XCTAssertEqual(try files(in: root), original)
    }

