    private func libraryWithoutCueFields(_ fields: [String]) throws -> Data {
        var library = try XCTUnwrap(
            JSONSerialization.jsonObject(with: historicalLibrary) as? [[String: Any]]
        )
        var clicks = try XCTUnwrap(library[0]["clicks"] as? [[String: Any]])
        for field in fields { clicks[0].removeValue(forKey: field) }
        library[0]["clicks"] = clicks
        return try JSONSerialization.data(withJSONObject: library, options: [.sortedKeys])
    }

    private func fixture() throws -> (URL, ProjectRepository, StorybirdStoragePreferences) {
        let root = FileManager.default.temporaryDirectory
            .appendingPathComponent("storybird-legacy-contract-\(UUID().uuidString)", isDirectory: true)
            .resolvingSymlinksInPath()
        let repository = ProjectRepository(
            rootURL: root.appendingPathComponent("default", isDirectory: true),
            sharedRootURL: root.appendingPathComponent("shared", isDirectory: true)
        )
        try repository.prepare()
        let domain = "storybird.legacy.contract.\(UUID().uuidString)"
        let defaults = try XCTUnwrap(UserDefaults(suiteName: domain))
