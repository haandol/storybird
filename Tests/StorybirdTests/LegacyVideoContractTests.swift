final class StrictProjectDecodingTests: XCTestCase {
    private func decoder(strict: Bool? = true) -> JSONDecoder {
        let decoder = JSONDecoder()
        if let strict { decoder.userInfo[.strictProjectEdits] = strict }
        decoder.nonConformingFloatDecodingStrategy = .convertFromString(
            positiveInfinity: "Infinity", negativeInfinity: "-Infinity", nan: "NaN"
        )
        return decoder
    }

    func test_strictStyle_invalidRawNumbersRejectBeforeClamping() throws {
        for (key, values) in [
            ("backgroundOpacity", ["-0.001", "1.001", #""Infinity""#, #""-Infinity""#, #""NaN""#]),
            ("fontSize", ["-1", "0", "0.999", #""Infinity""#, #""-Infinity""#, #""NaN""#]),
        ] {
            for value in values {
                let data = Data("{\"\(key)\":\(value)}".utf8)
                XCTAssertThrowsError(try decoder().decode(TextOverlayStyle.self, from: data)) { error in
                    guard case let DecodingError.dataCorrupted(context) = error else {
                        return XCTFail("Unexpected decoding error for \(key)=\(value): \(error)")
                    }
                    XCTAssertEqual(context.codingPath.last?.stringValue, key)
                }
            }
        }
    }

    func test_strictStyle_validBoundsAndAbsentValuesRetainDefaults() throws {
        XCTAssertEqual(try decoder().decode(TextOverlayStyle.self, from: Data("{}".utf8)), .default)
        for (opacity, size) in [(0.0, 1.0), (1.0, 96.0), (0.375, 17.5)] {
            let data = Data("{\"backgroundOpacity\":\(opacity),\"fontSize\":\(size)}".utf8)
            let style = try decoder().decode(TextOverlayStyle.self, from: data)
            XCTAssertEqual(style.backgroundOpacity, opacity)
            XCTAssertEqual(style.fontSize, size)
            XCTAssertEqual(style.backgroundHex, TextOverlayStyle.default.backgroundHex)
            XCTAssertEqual(style.foregroundHex, TextOverlayStyle.default.foregroundHex)
        }
        let onlyOpacity = try decoder().decode(
            TextOverlayStyle.self, from: Data(#"{"backgroundOpacity":0}"#.utf8)
        )
        XCTAssertEqual(onlyOpacity.fontSize, TextOverlayStyle.default.fontSize)
        let onlySize = try decoder().decode(
            TextOverlayStyle.self, from: Data(#"{"fontSize":1}"#.utf8)
        )
        XCTAssertEqual(onlySize.backgroundOpacity, TextOverlayStyle.default.backgroundOpacity)
    }

    func test_nonStrictStyle_absentOrFalseFlagPreservesLibraryClamping() throws {
        for strict: Bool? in [nil, false] {
            let low = try decoder(strict: strict).decode(
                TextOverlayStyle.self, from: Data(#"{"backgroundOpacity":-0.25,"fontSize":-2}"#.utf8)
            )
            XCTAssertEqual(low.backgroundOpacity, 0)
            XCTAssertEqual(low.fontSize, 1)
            let high = try decoder(strict: strict).decode(
                TextOverlayStyle.self, from: Data(#"{"backgroundOpacity":1.25,"fontSize":17}"#.utf8)
            )
            XCTAssertEqual(high.backgroundOpacity, 1)
            XCTAssertEqual(high.fontSize, 17)
        }
    }
